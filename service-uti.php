<h3 class="mt-4">Understanding UTI</h3>
<p>A <strong>urinary tract infection</strong> (UTI) in children is a bacterial infection of the bladder (cystitis) or kidneys (pyelonephritis). While common, recurrent UTIs in young children are often a critical sign of underlying urological anomalies that must be investigated.</p>

<h3 class="mt-4">Causes of UTI</h3>
<p>UTIs develop when bacteria enter the urinary tract. Contributing factors include:</p>
<ul class="about-list">
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Vesicoureteral Reflux (VUR):</strong> Urine flowing backward from the bladder to the kidneys, carrying bacteria.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Anatomical Obstructions:</strong> Conditions like PUJO or PUV that prevent complete drainage of urine.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Voiding Dysfunction:</strong> Infrequent voiding, constipation, or poor bladder hygiene.</li>
</ul>

<h3 class="mt-4">Signs of UTI</h3>
<p>Symptoms depend strongly on the child's age:</p>
<ul class="about-list">
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>In Infants:</strong> Unexplained high fever, irritability, poor feeding, vomiting, or diarrhea.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>In Older Children:</strong> Pain or burning sensation during urination, frequent urination, urgency, bedwetting, or foul-smelling urine.</li>
</ul>

            
<h3 class="mt-4">Why Early Intervention Matters</h3>
                <p>Ignoring a child's recurrent UTIs can lead to severe complications. Repeated infections cause inflammation that may result in renal scarring, which permanently damages the kidney tissue. Over time, this scarring can lead to early-onset hypertension and chronic kidney disease in adulthood. Addressing the root cause promptly ensures that your child's urinary system develops healthily without these risks.</p>
                
                <h3 class="mt-4">Comprehensive Care Approach</h3>
