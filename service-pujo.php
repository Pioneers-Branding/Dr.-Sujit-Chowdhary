<h3 class="mt-4">Understanding PUJO</h3>
<p><strong>Pelviureteric Junction Obstruction</strong> (PUJO) is a blockage or severe narrowing at the point where the kidney pelvis connects to the ureter. This impairs urine flow from the kidney to the bladder, causing urine to pool and swell the kidney (hydronephrosis).</p>

<h3 class="mt-4">Causes of PUJO</h3>
<p>PUJO is a congenital condition caused by:</p>
<ul class="about-list">
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Intrinsic Narrowing:</strong> Poorly developed muscle tissue at the junction, preventing normal peristaltic flow.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Crossing Vessel:</strong> An abnormal lower-pole renal blood vessel that crosses and compresses the ureter.</li>
</ul>

<h3 class="mt-4">Signs of PUJO</h3>
<p>Symptoms can present at birth or develop later in childhood:</p>
<ul class="about-list">
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Antenatal Hydronephrosis:</strong> Kidney swelling detected on routine pregnancy ultrasounds.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Flank or Side Pain:</strong> Recurrent abdominal or side pain, which may worsen after drinking fluids.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Recurrent UTIs:</strong> Urinary tract infections due to urine stasis.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Hematuria:</strong> Blood in the urine, sometimes triggered by minor trauma.</li>
</ul>

            
<h3 class="mt-4">Why Early Intervention Matters</h3>
                <p>Pelvic Ureteric Junction Obstruction (PUJO) restricts urine flow from the kidney to the bladder. If the obstruction is severe, the back-pressure can cause significant kidney damage, resulting in loss of renal function. Early diagnosis through prenatal and postnatal screening allows us to intervene before irreversible damage occurs, preserving the kidney and preventing recurrent infections and pain.</p>
                
                <h3 class="mt-4">Comprehensive Care Approach</h3>
                <p>We utilize a conservative, watchful waiting approach for mild cases, supported by advanced nuclear scans. When surgery is indicated, Dr. Chowdhary’s expertise in minimally invasive techniques ensures a highly successful pyeloplasty with a very short hospital stay. Our post-operative protocol involves careful monitoring to confirm unobstructed drainage and normal kidney growth.</p>
            
