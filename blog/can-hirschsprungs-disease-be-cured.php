            <h2>How Surgery Cures Hirschsprung's Disease: The Pull-Through</h2>
            <p>The definitive cure is called a pull-through operation. During this procedure, the pediatric surgeon removes the non-working section of the bowel and brings healthy intestine with normal ganglion cells down to connect with the anus, carefully preserving the anal sphincter muscles so the child can achieve normal bowel control.</p>

            <p>Surgeons choose from several established techniques depending on the child's age and how much bowel is involved:</p>

