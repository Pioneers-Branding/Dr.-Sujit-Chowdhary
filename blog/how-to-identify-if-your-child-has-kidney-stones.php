            <h2>What Exactly Are Pediatric Kidney Stones?</h2>
            <p>Kidney stones, known medically as <a href="https://en.wikipedia.org/wiki/Kidney_stone_disease" target="_blank" rel="noopener noreferrer">kidney stone disease</a> or renal calculi, are hard mineral deposits formed inside the kidneys. Normally, kidneys filter waste minerals through urine. However, when urine contains elevated levels of calcium, oxalate, or uric acid combined with low fluid intake, these minerals crystallize and grow into hard stones.</p>

            <p>Stones can remain painless while resting quietly inside the kidney. Symptoms begin when a stone shifts into the narrow ureter—the tube carrying urine to the bladder. The stone irritates the delicate mucosal wall and impedes urine drainage, triggering intense, spasmodic contractions termed renal colic.</p>

            <h2>5 Core Signs & Symptoms to Identify Kidney Stones in Children</h2>
            <p>Symptoms range from mild discomfort to acute distress. Watch for these five hallmark signs:</p>

            <h3>1. Sharp, Spasmodic Flank and Tummy Pain</h3>
            <p>Pain is the most common indicator in verbal children. Kidney stone pain typically occurs in sharp, cramping waves. As the ureter contracts to push the stone along, the child feels severe spasms in their <strong>flank</strong> (the side of the back just below the ribs). This pain often travels downward toward the lower abdomen, groin, or inner thigh.</p>

            <p>A helpful behavioral clue is extreme restlessness. While children with appendicitis prefer lying very still, a child suffering from a kidney stone cannot find a comfortable position. They toss and turn, pace the room, or curl into a ball trying to escape the pain.</p>

            <h3>2. Blood in the Urine (Hematuria)</h3>
            <p>As the jagged edges of a stone scrape the inner lining of the kidney or ureter, red blood cells leak into the urinary tract. Hematuria can present as visible pink, red, or tea-colored urine, or microscopic blood detectable only during laboratory urinalysis. If you notice discoloration, review our guide on <a href="causes-of-red-urine-in-a-child.php">causes of red urine in a child</a> to distinguish dietary discoloration from true bleeding.</p>

            <h3>3. Painful, Frequent, and Urgent Urination</h3>
            <p>When a stone moves down toward the bladder junction, it irritates the bladder wall. Children feel an urgent need to urinate frequently, often passing only a few drops with a burning sting. Because these signs mirror a urinary infection, parents should also consult our breakdown of <a href="child-bladder-infection-symptoms.php">child bladder infection symptoms</a> for comparative clarity.</p>

            <h3>4. Sudden Nausea and Repeated Vomiting</h3>
            <p>Because kidney and digestive nerve pathways overlap, acute urinary blockage reflexively causes intense nausea and repeated vomiting without loose stools, frequently mistaken for an upset stomach.</p>

            <h3>5. Fever and Chills (An Urgent Red Flag)</h3>
            <p>Uncomplicated stones rarely cause fever. However, if an impacted stone traps infected urine, it causes acute pyelonephritis. Severe flank pain combined with fever or shivering requires immediate emergency care.</p>

            <h2>Age-Specific Clues: From Toddlers to Adolescents</h2>
