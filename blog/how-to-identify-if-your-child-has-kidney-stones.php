                <h3>1. Can young children and toddlers really get kidney stones?</h3>
                <p>Yes. While widely regarded as an adult issue, kidney stones occur across all pediatric age groups, including infants. Diets high in sodium, low fluid intake, hot weather, and metabolic factors have led to a steady increase in childhood stone cases.</p>
            </div>

            <div class="faq-item">
                <h3>2. What is the most common symptom of a kidney stone in a child?</h3>
                <p>In older children, the most common sign is sudden, severe pain in the flank (side of the back) or lower abdomen that comes in waves. In toddlers and infants, the main symptoms are sudden crying spells, vomiting without diarrhea, irritability, and pink or red stains in the diaper.</p>
            </div>

            <div class="faq-item">
                <h3>3. How can I tell if my child has an ordinary stomach ache or a kidney stone?</h3>
                <p>An ordinary tummy ache is usually steady, central around the navel, and related to gas or constipation. A kidney stone produces sharp, colicky spasms in the flank or lower belly radiating to the groin, accompanied by vomiting, blood in urine, and restlessness where the child cannot sit comfortably.</p>
            </div>

            <div class="faq-item">
                <h3>4. Can a child pass a kidney stone naturally without surgery?</h3>
                <p>Yes. Small stones under 4 to 5 mm frequently pass on their own through increased hydration, mild pain medication, and medical expulsive therapy under pediatric urological supervision. Larger stones or those causing blockage require gentle, incision-free endoscopic laser treatment.</p>
            </div>

            <div class="faq-item">
                <h3>5. What tests are done to check for kidney stones in kids without radiation?</h3>
                <p>A high-resolution ultrasound of the kidneys, ureters, and bladder (USG KUB) is the primary first-line test. It is safe, painless, and completely free of radiation. Urine microscopy is also performed to check for red blood cells, infection, and mineral crystals.</p>
            </div>

            <div class="faq-item">
                <h3>6. What foods cause kidney stones in children?</h3>
                <p>Diets rich in ultra-processed snacks (chips, salted nuts), fast food with high sodium, and sugary caffeinated sodas increase stone risk. Crucially, parents should never stop giving their child milk or dairy, because normal dietary calcium actually binds oxalate in the intestine and prevents stone formation.</p>
            </div>

            <div class="faq-item">
                <h3>7. When should I take my child to the emergency room for kidney stone symptoms?</h3>
                <p>Seek immediate emergency medical care if severe flank or tummy pain is accompanied by high fever, shivering, continuous vomiting that prevents fluid intake, an inability to pass urine, or visible dark blood clots in the urine.</p>
            </div>

