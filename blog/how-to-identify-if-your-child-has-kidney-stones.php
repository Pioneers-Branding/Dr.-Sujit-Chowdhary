            <h2>How Doctors Accurately Diagnose Stones in Children</h2>
            <p>Child-safe diagnostics prioritize accuracy while avoiding unnecessary radiation:</p>

            <ul>
                <li><strong>High-Resolution Ultrasound (USG KUB):</strong> The primary diagnostic tool. Painless, non-invasive, and radiation-free, it measures stone size and detects hydronephrosis.</li>
                <li><strong>Low-Dose Pediatric CT Scan:</strong> Used when ultrasound cannot clearly view mid-ureteric stones, offering precise anatomical views with minimal radiation.</li>
                <li><strong>Urine Microscopy:</strong> Identifies red blood cells, infection markers, and diagnostic crystal shapes.</li>
                <li><strong>24-Hour Metabolic Workup:</strong> Analyzes blood and urine chemistry after stone passage to formulate a personalized prevention plan.</li>
            </ul>

            <h2>Treatment Options: Pediatric Stones Treatment in Delhi</h2>
            <p>Modern pediatric care focuses on gentle, incision-free techniques:</p>

            <h3>1. Medical Expulsive Therapy (MET)</h3>
            <p>Small stones measuring under 4 to 5 mm often pass on their own. Under pediatric urological guidance, children receive plenty of oral hydration and gentle medications that relax the ureter, allowing the stone to pass painlessly in urine.</p>

            <h3>2. RIRS (Retrograde Intrarenal Surgery) with Laser</h3>
            <p>For stones situated in the kidney or upper ureter that cannot pass naturally, RIRS is the gold standard. Using an ultra-slim, flexible pediatric scope introduced naturally through the urinary passage, the urologist reaches the stone. A fine Holmium laser fiber pulverizes the stone into dust without any skin cuts.</p>

            <h3>3. Mini-PCNL (Keyhole Surgery)</h3>
            <p>For larger stones over 1.5 cm, Mini-PCNL uses a pencil-tip puncture in the child's back to fragment and extract stones in a single daycare procedure with minimal discomfort.</p>

