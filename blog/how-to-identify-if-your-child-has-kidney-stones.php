                <li><strong>School-Aged Children (4–9 Years):</strong> Vague belly button pain, fear of using the toilet due to burning sensations, and sudden daytime wetting accidents.</li>
                <li><strong>Adolescents (10–18 Years):</strong> Classic one-sided flank pain radiating to the groin, visible pink or red urine, and severe restlessness.</li>
            </ul>

