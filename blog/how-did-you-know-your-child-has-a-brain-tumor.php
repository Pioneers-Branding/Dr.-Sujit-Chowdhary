                <h3>5. Can sudden clumsiness or poor balance in a child mean a brain tumor?</h3>
                <p>Yes. Tumors in the cerebellum interfere with coordination. A child may start stumbling on flat ground, walk with a wide wobbly gait (ataxia), struggle holding pencils or cups, or tilt their head persistently to one side.</p>
            </div>

            <div class="faq-item">
                <h3>6. What diagnostic scan is the gold standard for detecting pediatric brain tumors?</h3>
                <p>A contrast-enhanced Magnetic Resonance Imaging (MRI) scan of the brain and spine is the gold standard. It provides high-resolution, detailed cross-sectional images without exposing the child to radiation.</p>
            </div>

            <div class="faq-item">
                <h3>7. How quickly do pediatric brain tumor symptoms develop?</h3>
                <p>Fast-growing malignant tumors like medulloblastomas may cause noticeable symptoms over 2 to 6 weeks. Slower-growing benign gliomas may produce subtle signs that fluctuate and develop gradually over several months.</p>
            </div>

