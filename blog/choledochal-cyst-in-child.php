            <h3>The Classic Diagnostic Triad</h3>
            <p>In classical medical textbooks, choledochal cyst is described by a triad of three key symptoms:</p>
            <ol>
                <li><strong>Jaundice:</strong> Yellowing of the whites of the eyes (sclera) and skin due to impaired bile drainage.</li>
                <li><strong>Abdominal Pain:</strong> Episodic or constant pain located in the right upper quadrant of the stomach.</li>
                <li><strong>Palpable Mass:</strong> A smooth, firm lump or swelling felt by the doctor in the upper right abdomen.</li>
            </ol>
            <p><em>Note:</em> In modern clinical practice, only 20% to 30% of pediatric patients exhibit all three symptoms simultaneously. Many children present with only one or two isolated signs, or the cyst is discovered incidentally during routine abdominal sonography for unrelated issues.</p>

            <h3>Warning Signs Parents Should Never Ignore</h3>
            <ul>
                <li><strong>Pale or Clay-Colored Stools:</strong> When bile cannot enter the intestine, stool loses its natural brown color and turns chalky white, grey, or pale yellow.</li>
                <li><strong>Dark Tea-Colored Urine:</strong> Excess bilirubin filtered by the kidneys stains the urine dark yellow or brownish-tea color.</li>
                <li><strong>Recurrent Unexplained Fever with Chills:</strong> Indicates <strong>bacterial cholangitis</strong> (infection of stagnant bile inside the cyst), which is a serious medical emergency requiring urgent IV antibiotics.</li>
                <li><strong>Unexplained Abdominal Pain & Vomiting:</strong> May signify acute pancreatitis resulting from pancreatic juice reflux.</li>
            </ul>

            <h2>How is a Choledochal Cyst Diagnosed?</h2>
            <p>Accurate diagnostic evaluation is essential to confirm the presence of a choledochal cyst, delineate its precise anatomical structure, evaluate the pancreatic junction, and plan the surgical approach.</p>

            <h3>1. Antenatal / Prenatal Ultrasound</h3>
            <p>With widespread use of routine maternal ultrasound scans during pregnancy, many choledochal cysts are now detected in utero during the second or third trimester as a fluid-filled cystic mass under the fetal liver.</p>

            <h3>2. High-Resolution Abdominal Ultrasonography (USG)</h3>
            <p>Abdominal ultrasound is the primary non-invasive screening tool for pediatric liver and biliary tract conditions. It clearly visualizes cystic dilatation of the common bile duct, assesses gallbladder wall thickness, and evaluates intrahepatic bile duct involvement.</p>

            <h3>3. Magnetic Resonance Cholangiopancreatography (MRCP)</h3>
            <p><strong>MRCP is the gold-standard imaging modality</strong> for choledochal cyst evaluation in children. It provides high-resolution 3D images of the entire biliary tree, hepatic ducts, and pancreatic duct junction without exposing the child to ionizing radiation or invasive dye injections.</p>

            <h3>4. Laboratory Blood Tests (Liver Function Tests)</h3>
            <ul>
                <li><strong>Serum Bilirubin:</strong> Measures total and direct (conjugated) bilirubin levels to assess bile duct blockage.</li>
                <li><strong>Liver Enzymes:</strong> Elevated Alkaline Phosphatase (ALP), Gamma-Glutamyl Transferase (GGT), AST, and ALT indicate liver inflammation and biliary stasis.</li>
                <li><strong>Serum Amylase & Lipase:</strong> Evaluated to check for co-existing pancreatitis.</li>
            </ul>

            <h2>Complications of Untreated Choledochal Cyst</h2>
            <p>Leaving a choledochal cyst untreated or delaying surgical intervention carries grave health risks for a child. Because stagnant bile is prone to bacterial colonization and chronic irritation, untreated cysts can lead to severe long-term complications:</p>

            <ul>
                <li><strong>Recurrent Acute Cholangitis:</strong> Severe bacterial infection of the biliary tree causing high fever, sepsis, and liver abscess formation.</li>
                <li><strong>Acute & Chronic Pancreatitis:</strong> Inflammation of the pancreas due to pancreatic duct reflux or stone obstruction.</li>
                <li><strong>Biliary Cirrhosis & Portal Hypertension:</strong> Persistent bile backpressure causes progressive liver fibrosis, leading to irreversible liver failure over time.</li>
                <li><strong>Cyst Rupture:</strong> Spontaneous perforation of an inflamed cyst wall leading to life-threatening peritonitis (abdominal lining infection).</li>
                <li><strong>Malignancy (Cholangiocarcinoma):</strong> Long-term chronic inflammation in the cyst wall dramatically increases the risk of bile duct cancer later in adult life (up to 20-30% risk if left unexcised). This is why complete surgical removal of the cyst is mandatory.</li>
            </ul>

            <h2>Treatment Options for Choledochal Cyst in Children</h2>
            <p>There is no non-surgical or medical cure for a choledochal cyst. While medications like antibiotics or bile acid liquefiers can temporarily control active infections or jaundice, <strong>surgical excision is the only definitive treatment</strong>.</p>

