            <h2>Frequently Asked Questions (FAQs)</h2>

            <div style="margin-top: 25px;">
                <h3>Q1. What is the main cause of a choledochal cyst in a child?</h3>
                <p>The primary cause is a congenital structural anomaly called an Anomalous Pancreaticobiliary Junction (APBJ). This abnormal connection allows high-pressure pancreatic digestive juices to flow backward into the main bile duct, eroding its walls and causing it to dilate into a cyst over time.</p>

                <h3>Q2. Can a choledochal cyst dissolve or heal on its own without surgery?</h3>
                <p>No. A choledochal cyst is an irreversible structural malformation of the bile duct walls. It cannot dissolve, shrink, or cure itself through medications or diet. Complete surgical excision is mandatory to prevent dangerous infections, liver cirrhosis, and long-term cancer risks.</p>

                <h3>Q3. At what age should a child undergo choledochal cyst surgery?</h3>
                <p>Surgery is typically recommended as soon as the diagnosis is confirmed and the child is medically stable. In infants diagnosed antenatally or shortly after birth, surgery is usually performed between 1 to 6 months of age to prevent early liver inflammation and cholangitis.</p>

                <h3>Q4. What is Roux-en-Y hepaticojejunostomy and why is it necessary?</h3>
                <p>Roux-en-Y hepaticojejunostomy is the surgical procedure used to reconstruct the biliary pathway after the diseased cyst and gallbladder are removed. A section of the small intestine (jejunum) is reshaped into a dedicated channel and connected directly to the liver's bile duct, allowing bile to drain safely into the digestive tract.</p>

                <h3>Q5. What are the warning signs of cholangitis in a child with a choledochal cyst?</h3>
                <p>Cholangitis is a bacterial infection of stagnant bile within the cyst. Key warning signs include sudden high fever with shaking chills, worsening jaundice (yellow eyes/skin), severe right upper abdominal pain, vomiting, and dark tea-colored urine. Cholangitis requires emergency hospital admission and IV antibiotic treatment.</p>

                <h3>Q6. Is choledochal cyst surgery safe for infants and young children?</h3>
                <p>Yes. When performed by an experienced pediatric hepatobiliary surgeon using modern pediatric anesthesia and laparoscopic keyhole techniques, choledochal cyst excision is extremely safe, highly effective, and associated with high long-term success rates.</p>

                <h3>Q7. Will my child have to follow a special diet for life after surgery?</h3>
                <p>No! Once the Roux-en-Y reconstruction heals and bile flow is established, children can digest fat and process normal foods just like any other child. No lifelong dietary restrictions are necessary.</p>

