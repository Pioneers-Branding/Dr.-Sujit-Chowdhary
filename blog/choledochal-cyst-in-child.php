            <h3>Types of Choledochal Cysts (Todani Classification)</h3>
            <p>Pediatric surgeons classify choledochal cysts into five distinct categories based on their anatomical location and pattern of dilation, using the internationally accepted <strong>Todani Classification</strong> system:</p>
            <ul>
                <li><strong>Type I (Solitary Extrahepatic Dilation):</strong> The most common form (accounting for 80% to 90% of all cases), involving cystic or fusiform enlargement of the common bile duct outside the liver.</li>
                <li><strong>Type II (Extrahepatic Diverticulum):</strong> A rare pouch-like sac or diverticulum protruding outward from the wall of the common bile duct.</li>
                <li><strong>Type III (Choledochocele):</strong> Dilation situated within the wall of the duodenum at the lower end of the bile duct near the Ampulla of Vater.</li>
                <li><strong>Type IV (Multiple Dilation):</strong> Dilation affecting both intrahepatic (inside the liver) and extrahepatic (outside the liver) bile ducts.</li>
                <li><strong>Type V (Caroli's Disease):</strong> Rare cystic expansion confined strictly to the intrahepatic bile ducts within the liver tissue.</li>
            </ul>

            <h2>What Causes a Choledochal Cyst in a Child?</h2>
            <p>While the exact genetic or developmental trigger is still being researched, the widely accepted medical explanation for pediatric choledochal cysts centers on an anatomical defect known as an <strong>Anomalous Pancreaticobiliary Junction (APBJ)</strong> or pancreaticobiliary maljunction.</p>

            <h3>1. Anomalous Pancreaticobiliary Junction (APBJ)</h3>
            <p>In normal human anatomy, the common bile duct and the main pancreatic duct join together just as they enter the duodenal wall, sharing a short common channel controlled by a sphincter mechanism (the Sphincter of Oddi). In children born with an APBJ, these two ducts unite prematurely outside the intestinal wall, creating an abnormally long common channel.</p>

            <p>Because the pressure inside the pancreatic duct is higher than inside the bile duct, pancreatic digestive juices continuously flow backward (reflux) into the bile duct. These active pancreatic enzymes digest and erode the delicate elastic fibers of the bile duct wall. Over time, this chemical irritation weakens the duct wall, causing it to dilate and swell into a choledochal cyst.</p>

            <h3>2. Congenital Structural Weakness & Obstruction</h3>
            <p>In some cases, localized stenosis (narrowing) or dysmotility at the distal end of the common bile duct increases internal fluid pressure, contributing to ballooning of the proximal bile duct above the obstruction.</p>

