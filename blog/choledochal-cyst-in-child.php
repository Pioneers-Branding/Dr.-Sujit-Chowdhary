            <h2>What is a Choledochal Cyst in Children?</h2>
            <p>To understand what a choledochal cyst is, it helps to understand how the body produces and transports bile. The liver produces bile, a digestive fluid essential for breaking down fats and eliminating waste products from the bloodstream. Bile travels from the liver through a network of small tubes called <strong>bile ducts</strong> (the biliary tree), gets stored temporarily in the gallbladder, and eventually flows into the duodenum (the first part of the small intestine).</p>

            <p>A <a href="https://en.wikipedia.org/wiki/Choledochal_cyst" target="_blank" rel="noopener">choledochal cyst</a> is a congenital structural defect where parts of the extrahepatic or intrahepatic bile ducts undergo abnormal, pouch-like expansion or cystic dilation. Instead of remaining a smooth, narrow pipe, the bile duct balloons out. This structural malformation causes bile to stagnate (biliary stasis), leading to severe inflammation, bile duct stone formation, recurrent bacterial infections, and progressive liver tissue injury if not treated promptly.</p>

