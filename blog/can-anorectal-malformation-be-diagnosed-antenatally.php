            <h2>The Role of Fetal MRI in Prenatal Diagnosis</h2>
            <p>When routine ultrasound raises suspicion of an anorectal malformation or pelvic cyst, Fetal Magnetic Resonance Imaging (MRI) is the gold-standard confirmatory imaging technique.</p>

            <p>Fetal MRI uses strong magnetic fields and radio waves without any radiation, making it completely safe for both mother and baby during the second and third trimesters. Because fetal meconium naturally displays a bright signal on T1-weighted MRI sequences, radiologists can track the exact pathway of the distal colon down to the pelvic floor.</p>

            <p>Fetal MRI offers several distinct advantages:</p>
            <ul>
                <li>Pinpoints the level of the rectal pouch (high, intermediate, or low ARM).</li>
                <li>Delineates complex cloacal malformations and hydrocolpos in female fetuses.</li>
                <li>Evaluates the pelvic levator ani muscle complex essential for future bowel continent repair.</li>
                <li>Screens for associated spinal cord abnormalities, such as tethered cord or sacral agenesis.</li>
            </ul>

