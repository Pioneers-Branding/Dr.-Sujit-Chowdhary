            <h2>What is an Anorectal Malformation (ARM)?</h2>
            <p>To understand whether an anorectal malformation can be detected before birth, it is helpful first to understand what occurs during early fetal development.</p>

            <p>An Anorectal Malformation (ARM) is a spectrum of congenital defects that occur during the 4th to 12th weeks of embryonic development. During this early stage, the distal hindgut and urogenital tract split to form separate openings for bowel movement and urination. When this division is incomplete, the baby is born without a normal anal opening or with an abnormally positioned track.</p>

            <p>The spectrum of anorectal malformations includes several clinical variations:</p>

            <ul>
                <li><strong>Imperforate Anus:</strong> The anus is completely closed or missing, ending in a blind pouch inside the pelvis.</li>
                <li><strong>Perineal Fistula:</strong> The bowel opens through a narrow, abnormal tract on the skin close to where the anus should be.</li>
                <li><strong>Rectourethral or Rectovesical Fistula (Boys):</strong> The rectum connects directly to the urinary tract (urethra or bladder), allowing meconium to mix with urine.</li>
                <li><strong>Rectovaginal or Rectovestibular Fistula (Girls):</strong> The rectum opens into the vaginal vestibule or lower vagina.</li>
                <li><strong>Cloacal Malformation (Girls):</strong> A complex malformation where the digestive tract, vagina, and urinary tract merge into a single shared outlet on the perineum.</li>
            </ul>

