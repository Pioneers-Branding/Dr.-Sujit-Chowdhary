            <ul>
                <li><strong>V - Vertebral Anomalies:</strong> Sacral hemivertebrae or spinal cord anomalies.</li>
                <li><strong>A - Anorectal Malformation:</strong> Imperforate anus or fistula.</li>
                <li><strong>C - Cardiac Defects:</strong> Ventricular septal defect (VSD) or tetralogy of Fallot.</li>
                <li><strong>TE - Tracheoesophageal Fistula:</strong> Abnormal connection between food pipe and windpipe.</li>
                <li><strong>R - Renal / Kidney Anomalies:</strong> Single kidney, kidney duplication, or <strong><a href="../blog/hydronephrosis-in-children.php">Hydronephrosis in Children</a></strong>.</li>
                <li><strong>L - Limb Differences:</strong> Radial ray defects or thumb anomalies.</li>
            </ul>

            

