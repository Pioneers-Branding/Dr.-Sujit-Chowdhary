            <h2>Frequently Asked Questions (FAQs)</h2>

            <div style="margin-top: 25px;">
                <h3>Q1. Can an ultrasound scan detect imperforate anus before birth?</h3>
                <p>Yes, an antenatal ultrasound scan can raise suspicion of an imperforate anus or anorectal malformation (ARM), primarily by identifying indirect signs such as dilated fetal bowel loops, intraluminal meconium calcification (enterolithiasis), fetal pelvic cysts, or associated kidney and spine anomalies. Direct visualization of the anal dimple is challenging, but indirect markers prompt early expert evaluation.</p>

                <h3>Q2. At what week of pregnancy can anorectal malformation be suspected?</h3>
                <p>Anorectal malformation is usually suspected during the mid-trimester anomaly scan (level-II ultrasound) between weeks 18 and 22 of pregnancy. As the fetus grows and produces more meconium in the third trimester (28-34 weeks), bowel dilation or calcified meconium becomes more evident on ultrasound.</p>

                <h3>Q3. Why is ARM often missed during routine antenatal anomaly scans?</h3>
                <p>Routine antenatal ultrasound focuses on major organ structures like the brain, heart, spine, and kidneys. The anal sphincter and anal dimple are small soft-tissue structures deep within the fetal pelvis, making them difficult to image directly. Additionally, because fetal intestine does not contain gas before birth, distal bowel dilation may remain subtle.</p>

                <h3>Q4. Is fetal MRI safe and accurate for diagnosing anorectal malformations?</h3>
                <p>Yes. Fetal Magnetic Resonance Imaging (MRI) uses magnetic fields without radiation and is entirely safe during the second and third trimesters of pregnancy. It provides high-resolution soft-tissue contrast of the fetal pelvis, helping pediatric surgeons evaluate bowel position, pelvic muscle complex, and rule out spinal cord anomalies.</p>

                <h3>Q5. Does an antenatal ARM diagnosis mean a high-risk delivery is required?</h3>
                <p>Antenatal suspicion of ARM does not necessarily require a Caesarean section, but delivery should be planned at a tertiary medical center equipped with a Neonatal Intensive Care Unit (NICU) and an experienced pediatric surgical team for immediate post-birth evaluation.</p>

                <h3>Q6. Can anorectal malformation be treated before the baby is born?</h3>
                <p>No fetal or in-utero surgery is performed for anorectal malformations. Treatment is planned immediately after birth. Prenatal identification allows pediatric surgeons to prepare a tailored post-delivery surgical strategy.</p>

                <h3>Q7. What is the success rate of surgery for children with anorectal malformations?</h3>
                <p>With modern surgical techniques such as Posterior Sagittal Anorectoplasty (PSARP) and minimally invasive keyhole procedures, over 90% of children with low or intermediate ARM achieve excellent bowel control and live healthy, active lives.</p>

