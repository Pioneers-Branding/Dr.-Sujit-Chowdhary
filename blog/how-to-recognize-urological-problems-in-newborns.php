            <h2>Key Visual and Physical Signs in Newborns</h2>
            <p>Parents can spot potential <strong>neonatal urology symptoms</strong> by observing physical cues during diaper changes, feeding sessions, and bath times:</p>

            <h3>1. Abnormal Urinary Stream & Diaper Wetting Patterns</h3>
            <p>During the first 48 hours of life, a newborn may wet only 1 to 2 diapers per day due to physiological fluid shifts. However, by day 4 or 5, as milk intake increases, a healthy infant should produce 6 to 8 wet diapers daily. Key stream anomalies to watch for include:</p>
            <ul>
                <li><strong>Weak or Dribbling Stream:</strong> In baby boys, urine should exit in a clear, forceful arc. A weak, straining, or continuous slow dribble is a major warning sign.</li>
                <li><strong>Interrupted Voiding:</strong> Frequent straining, abdominal pushing, or crying while attempting to pass urine.</li>
                <li><strong>Inadequate Wet Diapers:</strong> Fewer than 4 wet diapers per day after the first week of life despite good fluid intake.</li>
            </ul>

            <h3>2. Urine Discoloration & Unusual Odor</h3>
            <p>While pinkish "brick dust" urate crystal spots are common in the first few days due to mild dehydration, persistent discoloration requires attention:</p>
            <ul>
                <li><strong>Blood-Tinged or Red Urine:</strong> True pink, red, or tea-colored urine indicates microscopic or gross blood (hematuria).</li>
                <li><strong>Cloudy or Foul-Smelling Urine:</strong> Strong, unpleasant odors or cloudy urine suggest bacterial contamination or urinary stasis.</li>
            </ul>

            <h3>3. Scrotal and Genital Swelling</h3>
            <p>The genital region should be inspected during daily hygiene care for signs such as:</p>
            <ul>
                <li><strong>Scrotal Hydrocele or Hernia:</strong> Fluid accumulation around the testicle causing a swollen, shiny scrotum. Read more on <strong><a href="../service/hernia-hydrocele.php">Infant Hernia & Hydrocele Care</a></strong>.</li>
                <li><strong>Undescended Testis (Cryptorchidism):</strong> Feeling an empty scrotal sac on one or both sides. Learn about <strong><a href="../service/absent-testis.php">Undescended / Absent Testis Evaluation</a></strong>.</li>
                <li><strong>Sudden Redness or Tenderness:</strong> Acute scrotal redness or hardness can signify neonatal testicular torsion, requiring immediate emergency assessment.</li>
            </ul>

            <h3>4. Misplaced Urethral Opening (Hypospadias)</h3>
            <p>In some male newborns, the urinary opening (meatus) is not located at the tip of the penis, but on the undersurface of the shaft, scrotum, or perineum. This common congenital variation is clinically termed <strong><a href="../service/hypospadias.php">Hypospadias</a></strong> and requires expert surgical reconstruction before toilet training.</p>

            <h3>5. Palpable Abdominal Masses</h3>
            <p>A swollen or firm lump felt in the baby's abdomen or flank during bathing can indicate an enlarged, fluid-filled kidney caused by severe <strong><a href="../service/hydronephrosis.php">Pediatric Hydronephrosis</a></strong> or a <strong><a href="../service/pujo.php">Pelviureteric Junction Obstruction (PUJO)</a></strong>.</p>

            <h2>Systemic and Behavioral Warning Signs</h2>
            <p>In addition to direct physical signs, systemic symptoms can point to underlying urological issues in early infancy:</p>

            <ul>
                <li><strong>Unexplained Neonatal Fever:</strong> A high temperature without cough or cold is often the single primary symptom of a <strong><a href="../service/uti.php">Pediatric Urinary Tract Infection (UTI)</a></strong> in young infants.</li>
                <li><strong>Irritability & Straining:</strong> Excessive crying, leg pulling, or distress specifically occurring during urination.</li>
                <li><strong>Poor Weight Gain (Failure to Thrive):</strong> Chronic urinary tract infections or reduced renal function can impair healthy growth and feeding.</li>
                <li><strong>Neonatal Jaundice or Lethargy:</strong> Severe urinary infections in early infancy can occasionally manifest as prolonged jaundice or sluggish responsiveness.</li>
            </ul>

