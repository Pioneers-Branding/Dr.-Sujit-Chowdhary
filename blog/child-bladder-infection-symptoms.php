            <h2>Primary Signs & Symptoms Parents Should Watch For</h2>
            <p>The clinical presentation of a bladder infection varies depending on the child's developmental age, verbal capability, and overall health status:</p>

            <h3>1. Pain or Burning During Urination (Dysuria)</h3>
            <p>The hallmark symptom of <strong>pediatric cystitis symptoms</strong> is sharp pain, burning, or stinging sensations while passing urine. Young children may cry, grimace, express fear of using the toilet, or actively hold back their urine to avoid discomfort.</p>

            <h3>2. Sudden Urinary Frequency & Urgency</h3>
            <p>Infected bladder walls become hyper-irritable and hyper-reactive. Children may feel an overwhelming, sudden urge to pass urine every 15 to 30 minutes throughout the day, often voiding only a few droplets at a time.</p>

            <h3>3. Daytime Wetting Accidents & Bedwetting</h3>
            <p>A child who has been fully potty-trained for months or years may suddenly experience new-onset <strong>daytime wetting accidents in children</strong> or secondary bedwetting (enuresis) due to involuntary bladder spasms caused by bacterial mucosal inflammation.</p>

            <h3>4. Urine Discoloration & Unusual Odor</h3>
            <p>Parents changing diapers or assisting in the bathroom should note distinct changes in urine appearance:</p>
            <ul>
                <li><strong>Cloudy or Hazy Appearance:</strong> Caused by the presence of white blood cells (pus/pyuria), shed epithelial cells, and bacterial clusters.</li>
                <li><strong>Pungent or Foul Odor:</strong> A distinctly strong, fishy, or ammonia-like smell indicating active bacterial metabolic waste.</li>
                <li><strong>Pink or Red Tint (Hematuria):</strong> Microscopic or visible blood droplets stemming from inflamed, raw bladder mucosal blood vessels.</li>
            </ul>

            <h3>5. Lower Abdominal or Pelvic Discomfort</h3>
            <p>Children often complain of a dull ache, pressure, or cramping located in the lower belly just above the pubic bone. They may hold their abdomen while trying to void or squirm uncomfortably while seated.</p>

            <h3>6. Symptoms in Infants and Non-Verbal Toddlers</h3>
            <p>Because infants cannot describe burning sensations, <strong>signs of UTI in children</strong> under 2 years of age are frequently non-specific, including:</p>
            <ul>
                <li>Unexplained low-grade or high fever without respiratory cold symptoms</li>
                <li>Persistent irritability, fussiness, or inconsolable crying during diaper changes</li>
                <li>Poor feeding, weak sucking, nausea, and vomiting</li>
                <li>Failure to gain weight or lethargy</li>
            </ul>

