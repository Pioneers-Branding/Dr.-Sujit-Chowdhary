            <h2>Understanding the Pelvi-Ureteric Junction</h2>
            <p>To understand the blockage, it helps to review normal kidney function. The kidneys filter waste and fluid from the blood to produce urine. Inside each kidney, funnel-like collection cups merge into a central chamber called the <strong>renal pelvis</strong>.</p>

            <p>At the lower end of this funnel lies the <strong>Pelvi-Ureteric Junction (PUJ)</strong>. This junction connects the wide renal pelvis to the <strong>ureter</strong>, the muscular drainage tube that carries urine down to the urinary bladder. Urine does not move by gravity alone; the walls of the junction and ureter contain specialized smooth muscle fibers that create wave-like contractions (peristalsis) to pump urine forward. When this junction is physically narrowed or fails to contract, urine accumulates inside the renal pelvis, creating backpressure that expands the kidney—a condition termed <strong><a href="hydronephrosis-in-children.php">pediatric hydronephrosis</a></strong>.</p>

