                    <h3><i class="fas fa-question-circle"></i> What happens if severe PUJO is left untreated in a child?</h3>
                    <p>Untreated severe obstruction causes continuous urine backpressure, leading to progressive thinning of the renal cortex, irreversible loss of kidney function, recurrent kidney infections, and stone formation.</p>
