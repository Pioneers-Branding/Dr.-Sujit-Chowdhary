            <h2>Secondary &amp; Acquired Causes in Children</h2>
            <p>Although rare in pediatric medicine, PUJO can be acquired during childhood through secondary medical conditions:</p>
            <ul>
                <li><strong>Recurrent Urinary Tract Infections (UTIs):</strong> Severe bacterial infections can produce chronic inflammation that heals with scar tissue, narrowing the junction lumen. Review warning signs in our article on <strong><a href="child-bladder-infection-symptoms.php">child bladder infection symptoms</a></strong>.</li>
                <li><strong>Pediatric Kidney Stones (Urolithiasis):</strong> A stone lodged at the junction causes mucosal trauma, leading to inflammatory strictures and microscopic or visible red urine, as detailed in our guide on <strong><a href="causes-of-red-urine-in-a-child.php">causes of red urine in a child</a></strong>.</li>
                <li><strong>Severe Vesicoureteric Reflux (VUR):</strong> Backward urine pressure elongates the ureter, causing tortuosity and secondary kinking at the junction.</li>
            </ul>

            <h2>Presentation Across Different Age Groups</h2>
            <p>The clinical presentation of PUJ obstruction varies significantly depending on the child's age:</p>

            <h3>In Newborns and Infants</h3>
            <p>Today, over 80% of infant PUJO cases are detected before birth on routine pregnancy ultrasounds. Most newborns have no outward symptoms at birth. When signs do occur, they usually manifest as unexplained fevers, irritability, poor feeding, or a palpable abdominal mass. To understand early indicators, explore our guide on <strong><a href="how-to-recognize-urological-problems-in-newborns.php">urological problems in newborns</a></strong>.</p>

            <h3>In Older Children and Teens</h3>
            <p>Older children typically experience intermittent symptoms driven by crossing vessels or partial narrowings. Hallmarks include recurring bouts of intense flank or tummy pain, nausea and vomiting (often mistaken for appendicitis), pain flaring after heavy fluid intake, and blood in the urine following physical play.</p>

            <h2>Diagnostic Evaluation: Finding the Underlying Cause</h2>
            <p>Determining the exact anatomical cause and evaluating whether the kidney is under threat requires specialized pediatric imaging:</p>
            <ol>
                <li><strong>Renal Ultrasound:</strong> Measures the renal pelvis diameter, caliceal dilation, and kidney cortical thickness.</li>
                <li><strong>MAG3 / DTPA Diuretic Renogram:</strong> A functional nuclear scan using a mild diuretic (furosemide) to measure actual drainage curves and split kidney function percentages.</li>
                <li><strong>MR Urography (MRU) / CT Angiography:</strong> Provides high-resolution anatomical mapping of renal blood vessels and collecting systems without ionizing radiation, ideal for detecting crossing vessels.</li>
                <li><strong>Micturating Cystourethrogram (MCU):</strong> Excludes associated bladder reflux when clinically indicated.</li>
            </ol>

