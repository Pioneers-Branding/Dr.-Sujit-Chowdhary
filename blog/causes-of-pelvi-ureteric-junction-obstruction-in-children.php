            <h2>Extrinsic Causes (External Mechanical Compression)</h2>
            <p>Extrinsic causes involve outside structures that mechanically pinch or distort the pelvi-ureteric junction. They represent the most common cause of PUJO diagnosed in school-aged children and adolescents:</p>

            <h3>1. Aberrant Crossing Lower Pole Vessels</h3>
            <p>In 20% to 30% of older children with PUJO, an accessory blood vessel courses across the junction. As the child grows or drinks large amounts of fluids, the expanding pelvis pushes against this taut vessel. The junction is compressed from the outside, causing intermittent obstruction and intense flank pain known as <strong>Dietl's crisis</strong>.</p>

            <h3>2. Fibrous Bands and Adhesions</h3>
            <p>Embryological connective tissues that fail to resorb cleanly form fibrous bands. These tether the upper ureter, pulling it into an acute kink that restricts normal drainage.</p>

            <h3>3. Associated Congenital Renal Variations</h3>
            <p>Children born with structural kidney variations have a higher susceptibility to extrinsic PUJ obstruction:</p>
            <ul>
                <li><strong>Horseshoe Kidney:</strong> Both kidneys are fused across the midline, forcing the ureters over the lower tissue bridge, predisposing to high insertion and compression.</li>
                <li><strong>Ectopic or Pelvic Kidneys:</strong> Kidneys located in the pelvis rather than the upper abdomen, often featuring atypical vessels and acute junction angles.</li>
            </ul>

