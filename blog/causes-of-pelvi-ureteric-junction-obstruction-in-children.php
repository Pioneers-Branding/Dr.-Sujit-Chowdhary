            <h2>Treatment Options: Protecting Renal Function</h2>
            <p>Management depends on whether the obstruction is impairing kidney drainage or causing functional decline:</p>

            <h3>1. Active Surveillance</h3>
            <p>Many infants with mild to moderate hydronephrosis have non-obstructive dilation that improves spontaneously as the urinary tract matures. These children are monitored safely through serial ultrasounds and renograms.</p>

            <h3>2. Surgical Correction: Dismembered Pyeloplasty</h3>
            <p>When scans confirm true obstruction, declining renal function, or severe symptoms, surgery is recommended. The gold standard procedure is the <strong>Anderson-Hynes Dismembered Pyeloplasty</strong>. The surgeon removes the narrowed junction segment, transposes crossing vessels if present, reduces redundant pelvic tissue, and reconstructs a wide, funnel-shaped passage with delicate absorbable sutures.</p>

