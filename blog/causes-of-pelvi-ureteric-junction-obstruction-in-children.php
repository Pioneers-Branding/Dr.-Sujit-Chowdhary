                    <h3><i class="fas fa-question-circle"></i> How does an aberrant crossing blood vessel cause PUJO in older children?</h3>
                    <p>An accessory lower pole renal blood vessel can run directly across the junction. As the child grows or drinks large amounts of fluids, the swelling pelvis presses against this taut vessel, causing an intermittent mechanical pinch that produces sudden flank pain.</p>
