            <h2>Red Flag Symptoms: When to Seek Immediate Medical Attention</h2>
            <p>Parents should immediately consult a pediatric specialist if red urine is accompanied by any of the following warning signs:</p>

            <ul>
                <li><i class="fas fa-exclamation-triangle" style="color: #e11d48; margin-right: 8px;"></i> <strong>High Fever or Chills:</strong> Indicates active kidney infection (pyelonephritis).</li>
                <li><i class="fas fa-exclamation-triangle" style="color: #e11d48; margin-right: 8px;"></i> <strong>Severe Abdominal or Flank Pain:</strong> Points toward kidney stones or urinary blockage.</li>
                <li><i class="fas fa-exclamation-triangle" style="color: #e11d48; margin-right: 8px;"></i> <strong>Facial Puffiness or Swelling:</strong> Swelling around eyes and legs suggests acute glomerulonephritis.</li>
                <li><i class="fas fa-exclamation-triangle" style="color: #e11d48; margin-right: 8px;"></i> <strong>Blood Clots in Urine:</strong> Seeing visible red blood clots requires prompt evaluation.</li>
                <li><i class="fas fa-exclamation-triangle" style="color: #e11d48; margin-right: 8px;"></i> <strong>Dramatically Reduced Urine Output:</strong> Inability to pass urine despite fluid intake.</li>
            </ul>

            <h2>Diagnostic Evaluation & Treatment Protocols</h2>
            <p>When evaluating <strong>causes of red urine in child</strong> health, a pediatric urologist performs:</p>

            <ol>
                <li><strong>Urinalysis & Microscopy:</strong> Testing urine for red blood cells, white blood cells, protein, and bacterial casts.</li>
                <li><strong>Urine Culture:</strong> Identifying specific bacterial strains to guide antibiotic therapy.</li>
                <li><strong>Renal Ultrasound:</strong> Non-invasive imaging of kidney anatomy, bladder, and checking for stones or blockages.</li>
                <li><strong>Blood Tests & Specialized Imaging:</strong> KFT, ASO titers, MCU/VCUG, or DMSA scans when structural anomalies are suspected.</li>
            </ol>

