            <h2>What is the Recurrence Risk for Future Pregnancies?</h2>
            <p>Parents often ask: <em>"If we have another baby, what is the chance that our next child will also have an imperforate anus?"</em></p>

            <p>Medical data provide very clear and reassuring odds:</p>
            <ul>
                <li><strong>General Population Risk:</strong> About 1 in 4,000 to 5,000 births (0.02%).</li>
                <li><strong>Recurrence Risk for Next Child:</strong> For parents of a child with an isolated, non-syndromic ARM, the recurrence risk in future pregnancies is only <strong>1% to 3%</strong>. This means there is a <strong>97% to 99% probability</strong> that future children will have normal anatomy.</li>
                <li><strong>Risk for Affected Individuals Having Children:</strong> An adult born with an isolated imperforate anus faces only a 1% to 3% chance of having an affected child, unless an autosomal dominant syndrome is involved.</li>
            </ul>

            <h2>When ARM Is Genetic: Recognized Syndromes</h2>
            <p>When an anorectal anomaly is genetic, pediatric specialists check for specific syndromes:</p>

            <h3>1. Currarino Syndrome (Currarino Triad)</h3>
            <p>Currarino syndrome is an autosomal dominant condition caused by mutations in the <strong><em>MNX1</em> gene</strong> on chromosome 7q36. It includes:</p>
            <ul>
                <li>Anorectal stenosis or low fistula.</li>
                <li>A crescent-shaped sacral bone defect (scimitar sacrum).</li>
                <li>A presacral mass (such as an anterior meningocele or teratoma).</li>
            </ul>
            <p>An affected parent has a 50% chance of passing the mutation to each child. Symptoms range from childhood constipation to the complete triad.</p>

            <h3>2. Townes-Brocks Syndrome</h3>
            <p>Townes-Brocks syndrome is an autosomal dominant condition linked to <strong><em>SALL1</em> gene</strong> mutations on chromosome 16q12.1. It presents with an imperforate anus, dysplastic ears with hearing loss, triphalangeal thumbs, and renal anomalies like <a href="hydronephrosis-in-children.php">hydronephrosis in children</a>.</p>

            <h3>3. Pallister-Hall Syndrome & Chromosomal Conditions</h3>
            <p>Pallister-Hall syndrome involves the <strong><em>GLI3</em> gene</strong>, featuring imperforate anus, extra digits, and hypothalamic hamartomas. Additionally, 2% to 4% of babies with Down syndrome (Trisomy 21) have an imperforate anus, as do infants with Cat Eye syndrome.</p>

            <h2>Is the VACTERL Association Hereditary?</h2>
            <p>Over 50% of infants with ARM have another congenital difference. When three or more co-occur, it is designated as <strong>VACTERL</strong> association (Vertebral, Anal, Cardiac, Tracheoesophageal, Renal, Limb).</p>

            <p>Despite involving multiple organs, <strong>VACTERL association is non-hereditary and sporadic</strong>. It reflects an early embryonic event rather than an inherited gene defect. The recurrence risk remains <strong>under 1%</strong>.</p>

