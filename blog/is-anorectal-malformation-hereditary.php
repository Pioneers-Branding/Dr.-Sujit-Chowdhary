            <h2>What is an Anorectal Malformation (ARM)?</h2>
            <p>An Anorectal Malformation (ARM), historically called an <strong>imperforate anus</strong>, is a spectrum of congenital defects where the lower digestive tract does not open normally. It occurs in roughly 1 in every 4,000 to 5,000 live births worldwide, affecting boys and girls alike.</p>

            <p>Between weeks 4 and 12 of pregnancy, the embryonic hindgut and urinary tract share a common chamber called the cloaca. A descending tissue partition (the urorectal septum) normally separates this chamber into the bladder in front and the rectum behind. If this division halts, an anorectal malformation occurs.</p>

            <p>Anomalies range from low defects (a narrow fistula opening on the perineal skin) to high defects (where the rectum opens into the bladder, urethra, or vagina). Clues may appear before delivery through <a href="can-anorectal-malformation-be-diagnosed-antenatally.php">antenatal diagnosis of anorectal malformation</a> or during newborn checks for <a href="how-to-recognize-urological-problems-in-newborns.php">urological problems in newborns</a>.</p>

            <h2>Is Anorectal Malformation Hereditary? (The Scientific Answer)</h2>
            <p>The clear, reassuring fact is that <strong>over 90% to 95% of anorectal malformations are NOT hereditary</strong>. They occur sporadically in families without any previous history of anorectal differences.</p>

            <p>Pediatric surgeons and geneticists categorize anorectal anomalies into two groups:</p>

            <h3>1. Isolated / Sporadic ARM (90% to 95% of Cases)</h3>
            <p>These occur at random under a <strong>multifactorial model of inheritance</strong>: minor polygenic traits interact with early intrauterine events during embryonic development. No single inherited parent gene is responsible.</p>

