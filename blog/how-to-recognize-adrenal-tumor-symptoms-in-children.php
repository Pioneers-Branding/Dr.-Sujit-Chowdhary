            <h2>Why Early Diagnosis and Evaluation Matter</h2>
            <p>Early identification of an adrenal tumor is vital for several reasons. First, malignant adrenal masses like neuroblastoma and adrenocortical carcinoma grow rapidly and can invade nearby blood vessels (such as the inferior vena cava) or metastasize to the liver, lungs, or bones if left untreated. Second, chronic hormone overproduction—such as severe pediatric hypertension or hypercortisolemia—can cause irreversible cardiovascular damage, bone density loss, and metabolic complications.</p>

            <p>Modern diagnostic workup for a suspected pediatric adrenal mass involves precise clinical testing:</p>
            <ol>
                <li><strong>High-Resolution Ultrasonography:</strong> The initial non-invasive screening tool to confirm the presence of a retroperitoneal mass above the kidney.</li>
                <li><strong>Contrast-Enhanced CT or MRI Imaging:</strong> Detailed cross-sectional imaging to assess tumor size, vascular invasion, organ relationships, and surgical feasibility.</li>
                <li><strong>24-Hour Urinary & Serum Catecholamines:</strong> Measuring Vanillylmandelic Acid (VMA), Homovanillic Acid (HVA), and free metanephrines to detect medullary tumors.</li>
                <li><strong>Comprehensive Serum Steroid Panel:</strong> Evaluation of DHEA-S, testosterone, 17-hydroxyprogesterone, morning cortisol, and ACTH levels.</li>
            </ol>

            <h2>Comprehensive Treatment Options for Pediatric Adrenal Tumors</h2>
            <p>Management of pediatric adrenal tumors requires a dedicated multidisciplinary team comprising a senior pediatric urologist/oncological surgeon, pediatric endocrinologist, and pediatric oncologist. Surgical resection remains the cornerstone of definitive cure for both benign and malignant adrenal tumors.</p>

            <h3>1. Laparoscopic and Robotic Adrenalectomy</h3>
            <p>For benign adenomas, small pheochromocytomas, and localized adrenocortical tumors, minimally invasive laparoscopic or robotic adrenalectomy is the gold standard. Using 3 to 4 tiny keyhole incisions, the surgeon precise dissects the tumor away from the renal vessels and liver/spleen while preserving surrounding tissues. Minimally invasive surgery dramatically reduces post-operative pain, leaves minimal scarring, and allows children to return home within 48 to 72 hours.</p>

            <h3>2. Open Radical Surgical Resection</h3>
            <p>Large malignant tumors, neuroblastomas with vascular encasement, or advanced carcinomas require open radical surgery to achieve complete gross resection (R0 margin) while protecting major vascular structures. In some cases, pre-operative neoadjuvant chemotherapy is administered to shrink the tumor prior to surgery.</p>

            <h3>3. Specialized Endocrine & Oncological Care</h3>
            <p>For children who have undergone complete <strong><a href="../service/adrenal-tumor.php">Adrenal Tumor Treatment in Delhi</a></strong>, careful post-operative hormone replacement therapy (such as hydrocortisone tapering) is managed by pediatric endocrinologists until the remaining adrenal gland fully recovers functionality.</p>

