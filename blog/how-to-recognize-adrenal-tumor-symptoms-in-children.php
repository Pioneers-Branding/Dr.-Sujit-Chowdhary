            <h2>Anatomy of the Adrenal Gland: Cortex vs. Medulla</h2>
            <p>To recognize why adrenal tumors cause specific symptoms, it is helpful to understand the basic structure of the adrenal gland. As shown in clinical anatomical diagrams, each adrenal gland consists of two distinct functional zones:</p>

            <ul>
                <li><strong>The Adrenal Cortex (Outer Layer):</strong> Responsible for producing corticosteroid hormones. The cortex is divided into three sub-zones that secrete <em>cortisol</em> (which regulates glucose metabolism and inflammation), <em>aldosterone</em> (which controls sodium, potassium, and blood pressure), and <em>adrenal androgens</em> (sex hormones like DHEA and testosterone).</li>
                <li><strong>The Adrenal Medulla (Inner Layer):</strong> Derived from neuroectodermal nerve tissues, the medulla produces catecholamines (adrenaline and noradrenaline). These hormones trigger the body’s "fight-or-flight" response, controlling heart rate, vascular resistance, and blood sugar spikes.</li>
            </ul>

            <p>Tumors arising from the cortex are called <strong>adrenocortical tumors (ACT)</strong>, which include benign adrenocortical adenomas and malignant adrenocortical carcinomas (ACC). Tumors arising from the medulla or sympathetic nervous chain include <strong>neuroblastoma</strong> (the most common adrenal malignancy in infants) and <strong>pheochromocytoma</strong> (a catecholamine-secreting tumor).</p>

            <h2>Primary Symptoms of Adrenal Tumors in Children</h2>
            <p>Pediatric adrenal tumor symptoms depend directly on whether the tumor actively secretes hormones (functioning tumor) or acts as a non-secretory mass that compresses neighboring organs. Clinicians categorize these signs into four main symptom clusters:</p>

            <h3>1. Virilization and Precocious Puberty (Androgen Overproduction)</h3>
            <p>Virilization is the most common presenting sign in children with adrenocortical tumors. When a tumor overproduces male hormones (androgens), young boys and girls experience premature development of adult sexual features, known as gonadotropin-independent precocious puberty.</p>
            <ul>
                <li><strong>Premature Hair Growth:</strong> Coarse pubic hair or axillary (underarm) hair developing in toddlers or young children under 6 years of age.</li>
                <li><strong>Facial Acne and Oily Skin:</strong> Adult-like facial breakout, persistent acne, and increased body odor.</li>
                <li><strong>Genital Enlargement:</strong> Enlargement of the clitoris in girls (clitoromegaly) or penile enlargement in boys without testicular growth.</li>
                <li><strong>Voice Deepening & Rapid Growth:</strong> A noticeably deeper voice pitch and a sudden, rapid growth spurt accompanied by advanced bone age.</li>
            </ul>

            <h3>2. Cushing's Syndrome Signs (Cortisol Overproduction)</h3>
            <p>When an adrenal tumor produces excess cortisol, it disrupts glucose regulation, fat distribution, and immune function, resulting in pediatric Cushing's syndrome:</p>
            <ul>
                <li><strong>"Moon Face" Appearance:</strong> A round, puffy, flushed facial appearance with prominent fullness in the cheeks.</li>
                <li><strong>Buffalo Hump & Central Obesity:</strong> Fat accumulation on the upper back, back of the neck, and trunk, while the child's arms and legs remain relatively thin.</li>
                <li><strong>Purple Skin Striae:</strong> Distinctive purple or reddish stretch marks on the abdomen, thighs, and buttocks.</li>
                <li><strong>Growth Failure:</strong> Despite rapid weight gain, the child's linear height velocity slows down dramatically, causing short stature relative to peers.</li>
                <li><strong>Mood Changes & Muscle Weakness:</strong> Irritability, emotional lability, fatigue, and proximal muscle weakness (difficulty climbing stairs or standing from a squat).</li>
            </ul>

            <h3>3. Autonomic Symptoms & High Blood Pressure (Pheochromocytoma)</h3>
            <p>Pheochromocytomas and catecholamine-secreting neuroblastomas pump excessive amounts of adrenaline and noradrenaline into the bloodstream, producing dramatic cardiovascular and autonomic effects:</p>
            <ul>
                <li><strong>Pediatric Hypertension:</strong> Unusually high blood pressure in a child, which may occur in paroxysms (sudden spikes) or remain persistently elevated.</li>
                <li><strong>Pounding Headaches & Palpitations:</strong> Severe, sudden headaches accompanied by a racing or pounding heart rate (tachycardia).</li>
                <li><strong>Profuse Sweating & Pallor:</strong> Excessive sweating, sudden facial paleness, tremors, and severe anxiety or panic-like episodes.</li>
            </ul>

            <h3>4. Abdominal Mass & Mechanical Compression Signs</h3>
            <p>Non-functioning adrenal tumors or advanced neuroblastomas may not cause hormonal changes. Instead, they present as physical abdominal masses or compress surrounding blood vessels and retroperitoneal structures:</p>
            <ul>
                <li><strong>Palpable Abdominal Lump:</strong> A firm, fixed, non-tender lump felt in the upper abdomen, flank, or side during routine bathing or dressing.</li>
                <li><strong>Abdominal Pain & Fullness:</strong> Vague belly pain, persistent abdominal distension, or a child complaining of feeling full quickly after eating only small bites.</li>
                <li><strong>Gastrointestinal Disturbances:</strong> Unexplained nausea, vomiting, constipation, or urinary frequency caused by tumor pressure on the stomach, intestines, or ureter.</li>
            </ul>

