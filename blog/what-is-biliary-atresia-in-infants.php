            <h3>3. Dark Tea-Colored Urine</h3>
            <p>Newborn urine is normally clear. In infants with biliary atresia, excess conjugated bilirubin spills into the urine, staining it dark yellow or tea-brown.</p>

            <h3>4. Abdominal Swelling & Firm Liver</h3>
            <p>As bile builds up, the liver becomes enlarged and firm. The baby's upper right abdomen may feel hard or swollen.</p>

            <h3>5. Poor Weight Gain & Vitamin Deficiencies</h3>
            <p>Without bile, infants struggle to absorb dietary fats, leading to poor weight gain and low levels of Vitamins A, D, E, and K.</p>

