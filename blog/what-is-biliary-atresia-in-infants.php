            <h2>Why Early Surgery Matters: The 60-Day Golden Window</h2>
            <p>When addressing <strong>what is biliary atresia in infants</strong>, timing is everything.</p>

            <p>Because trapped bile steadily damages liver cells, liver scarring advances every week. The primary surgical procedure—the <strong>Kasai procedure</strong>—has the highest success rate when performed early:</p>

            <ul>
                <li><strong>Surgery before 60 Days (8 Weeks) of Life:</strong> Up to 80% of infants establish effective bile drainage and clear their jaundice.</li>
                <li><strong>Surgery between 60 to 90 Days of Life:</strong> Success rates fall to 40%–50% as liver scarring worsens.</li>
                <li><strong>Surgery after 90 Days of Life:</strong> Success rates drop significantly due to advanced liver cirrhosis.</li>
            </ul>

            <p>This is why pediatric experts advise that any infant with jaundice lasting beyond 14 days receive prompt evaluation without delay.</p>

