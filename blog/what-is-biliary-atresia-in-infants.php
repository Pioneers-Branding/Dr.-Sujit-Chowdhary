            <h2>How is Biliary Atresia Diagnosed in Infants?</h2>
            <p>Diagnosing <strong>biliary atresia in infants</strong> involves precise tests to rule out other causes of newborn jaundice:</p>

            <h3>1. Fractionated Bilirubin Blood Test</h3>
            <p>Measures direct (conjugated) and indirect bilirubin. A direct bilirubin level over 1.0 mg/dL confirms bile duct obstruction.</p>

            <h3>2. Abdominal Ultrasound (USG)</h3>
            <p>Checks for the <em>triangular cord sign</em> (a cone of fibrous tissue at the liver base) and evaluates if the gallbladder is tiny or missing.</p>

            <h3>3. HIDA Scan (Hepatobiliary Scintigraphy)</h3>
            <p>A safe tracer tracks bile flow. In biliary atresia, the tracer enters the liver but fails to drain into the intestine.</p>

            <h3>4. Liver Biopsy</h3>
            <p>A small liver sample is examined under a microscope for duct blockage, bile plugs, and liver tissue scarring.</p>

            <h3>5. Intraoperative Cholangiogram (Confirmative Test)</h3>
            <p>Contrast dye is injected into the bile ducts during a minor keyhole procedure. If dye does not reach the intestine, biliary atresia is confirmed, and the surgeon performs the Kasai operation immediately.</p>

            <h2>Surgical Treatment: The Kasai Procedure</h2>
            <p>Biliary atresia cannot be cured with medications or light therapy. <strong>Surgery is the only effective treatment</strong>.</p>

            <h3>The Kasai Procedure (Kasai Portoenterostomy)</h3>
            <p>The Kasai procedure is the gold-standard surgical operation for biliary atresia in infants:</p>

            <ol>
                <li><strong>Removal of Blocked Ducts:</strong> The surgeon removes the scarred external bile ducts and gallbladder.</li>
                <li><strong>Intestinal Loop Connection:</strong> A loop of the infant's small intestine (jejunum) is brought up and connected directly to the liver base (porta hepatis).</li>
                <li><strong>Bile Drain Restoration:</strong> Bile drains directly from microscopic channels in the liver into the small intestine, restoring digestion and waste clearance.</li>
            </ol>

