            <h2>What is Biliary Atresia in Infants? (Anatomy & Bile Flow)</h2>
            <p>To understand <strong>biliary atresia in infants</strong>, it helps to understand how the liver and bile ducts work in a healthy baby.</p>

            <p>The liver produces a yellowish-green fluid called <strong>bile</strong>, which serves two major purposes in an infant's body:</p>
            <ul>
                <li><strong>Digestion:</strong> Bile salts break down dietary fats and fat-soluble vitamins (Vitamins A, D, E, and K) in the intestine, helping the baby absorb nutrients and gain weight.</li>
                <li><strong>Waste Clearance:</strong> Bile transports waste products, including <em>bilirubin</em> (a byproduct of broken-down red blood cells), out of the liver to be excreted in stool.</li>
            </ul>

            <p>In a healthy infant, bile travels from liver cells into small bile ducts, which join to form larger ducts outside the liver. Bile passes into the gallbladder and drains into the duodenum (small intestine).</p>

            <p>In an infant with <a href="https://en.wikipedia.org/wiki/Biliary_atresia" target="_blank" rel="noopener">biliary atresia</a>, the bile ducts outside or inside the liver become severely inflamed, narrowed, or replaced by fibrous scar tissue. Because the bile ducts are blocked, bile cannot leave the liver.</p>

            <p>Trapped bile accumulates inside liver tissue (biliary stasis), causing cell damage, inflammation, and rapid scarring. Simultaneously, because bile cannot reach the gut, fat digestion drops, and excess bilirubin leaks into the bloodstream, turning the skin yellow and urine dark.</p>

            <div class="highlight-info-box">
                <h4><i class="fas fa-info-circle"></i> Understanding the Medical Term</h4>
                <p>The word <em>"atresia"</em> means the abnormal closure or absence of a body opening. <strong>Biliary atresia</strong> literally refers to the blockage or absence of the normal bile ducts that transport bile from the liver into the digestive tract.</p>
            </div>

            <h2>Types of Biliary Atresia in Infants</h2>
            <p>Pediatric specialists classify <strong>biliary atresia in infants</strong> into two primary clinical types:</p>

            <h3>1. Perinatal / Acquired Biliary Atresia (80%–85% of Cases)</h3>
            <p>This is the most common form. Infants appear healthy at birth. However, between 2 to 4 weeks of age, jaundice fails to disappear, stools become pale, and bile duct scarring progresses rapidly.</p>

            <h3>2. Embryonic / Congenital Biliary Atresia (15%–20% of Cases)</h3>
            <p>In embryonic biliary atresia, the bile duct blockage develops during fetal growth. Babies are born with jaundice or develop severe jaundice immediately after birth. This form is often linked with other congenital conditions, such as heart defects or splenic anomalies.</p>

            <h2>What Causes Biliary Atresia in Infants?</h2>
            <p>Parents often ask: <em>"Why did my baby develop biliary atresia?"</em> or <em>"Could this have been prevented during pregnancy?"</em></p>

            <p>It is reassuring for parents to know that <strong>biliary atresia is NOT caused by anything done during pregnancy</strong>. It is not caused by medications, diet, or birth injury, nor is it a inherited genetic illness passed down from parents.</p>

            <p>Medical researchers believe biliary atresia is triggered by an inflammatory reaction shortly after birth that damages bile duct cells. Potential causes under study include:</p>

            <ul>
                <li><strong>Post-Viral Immune Response:</strong> Perinatal exposure to common viruses (such as rotavirus or reovirus) may trigger an autoimmune response where the baby's immune system mistakenly attacks bile duct tissue.</li>
                <li><strong>Developmental Disruption:</strong> Minor blood supply issues during early bile duct formation.</li>
                <li><strong>Bile Acid Toxicity:</strong> Sensitivity to certain bile components that irritate delicate infantile duct walls.</li>
            </ul>

            <h2>Recognizing Early Symptoms of Biliary Atresia in Infants</h2>
            <p>Early symptom recognition is the most critical step in treating <strong>biliary atresia in infants</strong>. Parents should look for these key warning signs during the first few weeks of life:</p>

            <h3>1. Persistent Infant Jaundice (Yellowing of Skin & Eyes)</h3>
            <p>Jaundice causes yellowing of the skin and whites of the eyes. While mild jaundice occurs in many newborns, <strong>jaundice that lasts longer than 14 days is NEVER normal</strong> and requires immediate blood testing for direct (conjugated) bilirubin.</p>

            <h3>2. Pale, Clay-Colored, or White Stools (Acholic Stools)</h3>
            <p>This is the classic symptom of biliary atresia. Normal baby stool is bright yellow, mustard, or green due to bile. When bile ducts are blocked, stool loses its color, turning pale yellow, chalky white, or clay-colored.</p>

