                <h3>Q1. What is biliary atresia in infants?</h3>
                <p>Biliary atresia in infants is a rare congenital condition where the bile ducts outside or inside the liver become blocked, narrowed, or scarred. This prevents bile from draining into the intestines, causing bile buildup, persistent infant jaundice, pale stools, and direct bilirubin elevation.</p>

                <h3>Q2. How can parents tell normal newborn jaundice apart from biliary atresia?</h3>
                <p>Normal physiological jaundice fades within 10 to 14 days of birth. Biliary atresia jaundice persists past 2 weeks and is accompanied by pale or clay-colored (acholic) stools, dark tea-colored urine, and high direct (conjugated) bilirubin.</p>

                <h3>Q3. What causes biliary atresia in babies?</h3>
                <p>The exact cause is unknown, but medical research suggests an inflammatory or autoimmune response triggered after birth by a viral infection damages the bile ducts. It is not inherited or caused by anything during pregnancy.</p>

                <h3>Q4. Is biliary atresia in infants curable with medication?</h3>
                <p>No. Biliary atresia cannot be cured with medications, light therapy, or diet. Surgical intervention (the Kasai procedure) is mandatory to establish bile flow from the liver into the digestive tract.</p>

                <h3>Q5. What is the Kasai procedure for biliary atresia?</h3>
                <p>The Kasai procedure (portoenterostomy) is a specialized pediatric operation where blocked bile ducts are removed and a loop of the infant's small intestine is connected directly to the liver surface to restore bile drainage.</p>

