<h3 class="mt-4">Understanding PUV</h3>
<p><strong>Posterior Urethral Valves</strong> (PUV) is a congenital condition in baby boys where abnormal membrane folds in the urethra block urine flow out of the bladder. The severe backup pressure damages the bladder wall, ureters, and developing kidneys.</p>

<h3 class="mt-4">Causes of PUV</h3>
<p>PUV is a developmental anomaly that occurs early in gestation:</p>
<ul class="about-list">
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Developmental Error:</strong> Failure of the embryological folds (wolffian duct remnants) to regress, leaving valve-like leaflets in the prostatic urethra.</li>
</ul>

<h3 class="mt-4">Signs of PUV</h3>
<p>Symptoms range from severe prenatal signs to postnatal voiding issues:</p>
<ul class="about-list">
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Bilateral Hydronephrosis:</strong> Swelling of both kidneys and low amniotic fluid (oligohydramnios) on prenatal ultrasound.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Weak Urine Stream:</strong> A slow, dribbling, or interrupted stream in a newborn male.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Distended Bladder:</strong> A hard, palpable bladder mass in the lower abdomen.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Recurrent UTIs:</strong> Severe urinary tract infections accompanied by high fevers.</li>
</ul>

            
<h3 class="mt-4">Why Early Intervention Matters</h3>
                <p>Posterior Urethral Valves (PUV) is a urological emergency in newborn boys. The severe blockage can cause rapid kidney and bladder deterioration. Immediate relief of the obstruction is vital to halt further damage and give the kidneys a chance to recover. Delayed treatment can lead to end-stage renal disease, requiring dialysis or a kidney transplant early in life.</p>
                
                <h3 class="mt-4">Comprehensive Care Approach</h3>
                <p>Treating PUV is a marathon, not a sprint. Even after the valves are successfully ablated, the child may have a "valve bladder" that functions poorly. Our comprehensive care includes regular urodynamic studies, kidney function tests, and continuous bladder management to protect the upper urinary tract and ensure the best long-term outcome for your child.</p>
            
