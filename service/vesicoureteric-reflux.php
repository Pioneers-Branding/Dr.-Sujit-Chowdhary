                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What is Vesicoureteric Reflux (VUR) and how does it occur?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Vesicoureteric Reflux (VUR) is a congenital condition where the flap-valve mechanism between the ureter and bladder is incompetent, allowing urine to flow backwards toward the kidneys during bladder contraction.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>How is VUR diagnosed and graded?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>VUR is diagnosed using a Micturating Cystourethrogram (MCU / VCUG) imaging scan and graded from Grade I (mild reflux into lower ureter) to Grade V (severe reflux with extreme dilation and tortuosity of ureters and kidneys).</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>Does VUR always require surgical intervention?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>No, lower grades (Grade I–III) often resolve spontaneously as the child grows and the ureteric tunnel lengthens. Low-grade VUR is managed conservatively with continuous low-dose prophylactic antibiotics and regular monitoring.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What is the endoscopic STING (Deflux) procedure?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>STING is a minimally invasive daycare procedure where a pediatric urologist inserts a miniature cystoscope into the bladder and injects a biocompatible gel (Deflux) under the ureter opening, creating a firm bulge that acts as a one-way valve to stop backflow.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>When is open or robotic ureteral reimplantation recommended?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Ureteral reimplantation is recommended for high-grade reflux (Grade IV–V), persistent reflux that fails endoscopic STING treatment, or when breakthrough kidney infections occur despite antibiotic prophylaxis.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>Can untreated VUR lead to permanent kidney damage?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Yes, repeated kidney infections (pyelonephritis) caused by untreated VUR lead to renal scarring, loss of kidney function, stunted renal growth, and an increased risk of high blood pressure in adulthood.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What follow-up care is needed after VUR treatment?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Following STING or reimplantation, follow-up renal ultrasounds and DMSA kidney scans are scheduled at 3 to 6 months to confirm that reflux has ceased and that kidney growth and function remain healthy.</p>
