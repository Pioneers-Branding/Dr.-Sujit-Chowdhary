                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What is Biliary Atresia and how does it affect newborns?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Biliary atresia is a rare, life-threatening liver condition in infants where the bile ducts outside or inside the liver become inflamed and blocked. This prevents bile from draining into the intestines to digest fats, leading to bile accumulation in the liver, jaundice, and progressive liver cirrhosis if not treated early.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What is the Kasai Portoenterostomy procedure?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>The Kasai procedure is the primary surgical treatment for biliary atresia. During surgery, the damaged external bile ducts are removed, and a loop of the infant's small intestine is attached directly to the liver surface (portoenterostomy) to establish a new pathway for bile drainage.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What is the ideal age for Kasai surgery?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Early surgical intervention is critical. The Kasai procedure yields the highest success rate when performed before 60 days (2 months) of age. Operating early prevents irreversible liver scarring and maximizes the chance of restoring normal bile flow.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What early warning signs should parents look out for?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Key warning signs in infants include persistent jaundice (yellowish skin and eyes) lasting beyond 2 weeks of life, pale clay-colored or white stools, dark tea-colored urine, and an enlarged, firm abdomen due to liver swelling.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>Is a liver transplant always necessary for children with biliary atresia?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>A successful Kasai procedure can restore bile flow and preserve native liver function for many years, delaying or avoiding the need for a liver transplant. However, some children who develop progressive liver scarring over time may eventually require a liver transplant in later childhood.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>How long is the hospital recovery after Kasai surgery?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Infants typically stay in the hospital for 7 to 10 days post-surgery. During this time, the surgical team monitors bile drainage, provides intravenous nutrition, manages post-op recovery, and starts special medications to encourage bile flow.</p>
                    </div>
                </div>

                <div class="faq-item">
