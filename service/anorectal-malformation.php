                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>After anoplasty or PSARP, routine home dilations using smooth Hegar dilators are performed for several weeks to prevent surgical scar tissue from contracting and narrowing the new anal orifice.</p>
                    </div>
                </div>

