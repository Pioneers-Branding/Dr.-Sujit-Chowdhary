                        <h5>Is immediate emergency surgical treatment required after birth?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Yes, an evaluation within the first 24 to 48 hours of life is essential. High-type defects require a temporary colostomy to divert stool safely, whereas lower-type defects can often undergo primary anoplasty.</p>
