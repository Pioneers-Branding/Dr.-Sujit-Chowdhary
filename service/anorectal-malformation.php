                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What is the PSARP (Peña) procedure?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Posterior Sagittal Anorectoplasty (PSARP) is the gold-standard surgical reconstruction for ARM. The surgeon carefully identifies the pelvic muscle sphincter complex and places the mobilized rectal pouch directly within the muscle center to optimize future bowel control.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
                        <h5>What is laparoscopic LAARP surgery?</h5>
                        <i class="fas fa-plus"></i>
                    </div>
                    <div class="faq-content">
                        <p>Laparoscopic-Assisted Anorectal Pull-through (LAARP) is an advanced keyhole surgical technique used for high rectourethral fistulas, allowing high-definition camera visualization to dissect the rectum and pull it down with minimal muscle disruption.</p>
                    </div>
                </div>

                <div class="faq-item">
                    <div class="faq-header">
