    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Balanitis Xerotica Obliterans (BXO):</strong> Chronic inflammatory skin condition creating a rigid, whitish scar ring at the preputial tip.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Forced Retraction Trauma:</strong> Premature or forceful pulling back of a tight foreskin causing micro-tears and secondary cicatricial scarring.</li>
</ul>

