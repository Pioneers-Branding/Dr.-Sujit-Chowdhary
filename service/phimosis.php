    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Recurrent Balanoposthitis:</strong> Repeated redness, swelling, or purulent discharge underneath the foreskin.</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Painful Voiding & UTIs:</strong> Straining to pass urine or developing secondary <a href="uti.php">urinary tract infections</a>.</li>
</ul>

