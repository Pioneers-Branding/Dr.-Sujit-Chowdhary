<h3 class="mt-4">Understanding Paediatric GI</h3>
<p><strong>Paediatric gastrointestinal (GI) conditions</strong> include a variety of congenital and acquired surgical disorders of the esophagus, stomach, intestines, liver, and biliary tree, such as appendicitis, bowel obstruction, and abdominal cysts.</p>

<h3 class="mt-4">Causes of Paediatric GI</h3>
<p>These conditions arise from diverse developmental and inflammatory processes:</p>
<ul class="about-list">
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Congenital Anomalies:</strong> Development errors during fetal growth leading to structural blockages (e.g. malrotation).</li>
    <li><i class="fas fa-check-circle" style="color: var(--secondary-teal); margin-right: 8px;"></i> <strong>Acute Inflammation:</strong> Infections or obstructions of organs, such as acute appendicitis or gallstones.</li>
</ul>

<h3 class="mt-4">Signs of Paediatric GI</h3>
<p>GI symptoms in children require prompt evaluation:</p>
<ul class="about-list">
